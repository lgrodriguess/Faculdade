    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed

        Hospede hospede = new Hospede();

        hospede.setNome(edtNomeHosp.getText());
        hospede.setDocumento(edtDocumentoHosp.getText());

        Endereco endereco = new Endereco();

        endereco.setCEP(edtCepHosp.getText());
        endereco.setCidade(edtCidadeHosp.getText());
        endereco.setRua(edtRuaHosp.getText());
        endereco.setNum(
            Integer.parseInt(edtNumeroEndHosp.getText())
        );

        hospede.setEndereco(endereco);

        hospede.getContatos().add(
            edtContatoHosp.getText()
        );


        gerenciadorHospede.add(hospede);
        try {
            gerenciadorHospede.gravarNoArquivo("hospedes.json");
        } catch (IOException ex) {
            Logger.getLogger(DlgCadHospedes.class.getName()).log(Level.SEVERE, null, ex);
        }


        System.out.println("Hospede cadastrado!");


        dispose();
    
    }//GEN-LAST:event_btnConfirmarActionPerformed

