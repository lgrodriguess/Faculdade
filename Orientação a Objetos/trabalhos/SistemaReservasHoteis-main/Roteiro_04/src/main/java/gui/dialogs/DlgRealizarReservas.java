    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
           if(  hospedeSelecionado == null ||
        quartoSelecionado == null ||
        checkInSelecionado == null ||
        checkOutSelecionado == null
    ) {

        System.out.println("Preencha todos os dados da reserva!");

        return;
    }

    Reserva reserva = new Reserva();

    reserva.setQuarto(quartoSelecionado);
    reserva.setHospede(hospedeSelecionado);
    reserva.setCheckIn(checkInSelecionado);
    reserva.setCheckOut(checkOutSelecionado);
    
    gerenciadorReservas.carregarDoArquivo("reservas.json");
    gerenciadorReservas.add(reserva);
        try {
            gerenciadorReservas.gravarNoArquivo("reservas.json");
            System.out.println("reserva salva no arquivo!");
        } catch (IOException ex) {
            Logger.getLogger(DlgRealizarReservas.class.getName()).log(Level.SEVERE, null, ex);
        }
    
    System.out.println("Reserva salva!");

    System.out.println(
        "Quantidade de reservas: " +
        gerenciadorReservas.getReservas().size()
    );

    dispose();
    }//GEN-LAST:event_btnConfirmarActionPerformed

