    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        Quarto quarto = new Quarto();

    quarto.setNum(
    Integer.parseInt(edtNumeroQuarto.getText())
);

        quarto.setTipo(edtTipoQuarto.getText());

    quarto.setPreco(
        Double.parseDouble(edtPrecoPorNoite.getText())
    );

    gerenciadorQuarto.add(quarto);
        try {
            gerenciadorQuarto.gravarNoArquivo("quarto.json");
        } catch (IOException ex) {
            Logger.getLogger(DlgCadQuarto.class.getName()).log(Level.SEVERE, null, ex);
        }
    System.out.println("Quarto cadastrado!");

    dispose();
    }//GEN-LAST:event_btnConfirmarActionPerformed

